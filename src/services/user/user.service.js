const OUT_OF_SERVICE_MSG = "Out of service area definition";

const ADDRESS_TABLE_SQL = `
CREATE TABLE IF NOT EXISTS public.tbl_user_addresses (
  id bigint generated by default as identity primary key,
  user_id bigint not null,
  label varchar(60) default 'Home',
  recipient_name varchar(80),
  phone_number varchar(12),
  street text,
  district varchar(45),
  state varchar(45),
  landmark varchar(100),
  pin_code varchar(45),
  is_default boolean default false,
  inserted_at timestamptz default now(),
  updated_at timestamptz default now()
)`;

let addressBookReady = false;

const ensureAddressBookTable = async () => {
  if (addressBookReady) return;
  await runMysqlQuery(ADDRESS_TABLE_SQL);
  await runMysqlQuery(`CREATE INDEX IF NOT EXISTS tbl_user_addresses_user_index ON public.tbl_user_addresses (user_id)`);
  await runMysqlQuery(`CREATE UNIQUE INDEX IF NOT EXISTS tbl_user_addresses_one_default ON public.tbl_user_addresses (user_id) WHERE is_default = true`);
  addressBookReady = true;
};

const getFranchiseForPincode = async (pincode) => {
  const normalizedPincode = `${pincode || ""}`.trim();
  if (!normalizedPincode) return null;
  const param = JSON.stringify([normalizedPincode]);
  const franchiseSql = `SELECT user_id FROM tbl_franchise_details WHERE JSON_CONTAINS(zip_codes, ?)`;
  const franchise = await runMysqlQueryWithParam(franchiseSql, [param]);
  return franchise.length ? franchise[0] : null;
};

