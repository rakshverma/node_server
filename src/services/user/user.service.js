const addUserAddress = async (street, state, district, pincode, landmark, user_id) => {
  console.log("user_id = ", user_id);
  try {
    await ensureAddressBookTable();
    const normalizedPincode = `${pincode || ""}`.trim();
    const normalizedDistrict = `${district || ""}`.trim();
    const normalizedLabel = "Home";
    const franchise = await getFranchiseForPincode(normalizedPincode);
    if (!normalizedPincode || !franchise?.user_id) {
      return { status: false, msg: OUT_OF_SERVICE_MSG, responseObj: [] };
    }
    const sql = `select district from mst_pin_codes where pin_code=?`;
    const check = await runMysqlQueryWithParam(sql, [normalizedPincode]);
    if (!check.length) return { status: false, msg: OUT_OF_SERVICE_MSG, responseObj: [] };
    if (`${check[0].district || ""}`.trim().toLowerCase() !== normalizedDistrict.toLowerCase()) {
      return { status: false, msg: "District and pin code does not match", responseObj: [] };
    }
    const addressList = await runMysqlQueryWithParam("SELECT id FROM tbl_user_addresses WHERE user_id=? ORDER BY is_default DESC, id ASC", [user_id]);
    const addressId = addressList?.[0]?.id;
    if (addressId) {
      await runMysqlQueryWithParam("UPDATE tbl_user_addresses SET is_default=false WHERE user_id=?", [user_id]);
      await runMysqlQueryWithParam(
        "UPDATE tbl_user_addresses SET label=?, street=?, state=?, district=?, pin_code=?, landmark=?, is_default=true, updated_at=now() WHERE id=? AND user_id=?",
        [normalizedLabel, street, state, normalizedDistrict, normalizedPincode, landmark, addressId, user_id]
      );
    } else {
      await runMysqlQueryWithParam(
        "INSERT INTO tbl_user_addresses (user_id, label, street, state, district, pin_code, landmark, is_default) VALUES (?,?,?,?,?,?,?,true)",
        [user_id, normalizedLabel, street, state, normalizedDistrict, normalizedPincode, landmark]
      );
    }
    const userCheck = await runMysqlQueryWithParam("select id from tbl_user_details where user_id=?", [user_id]);
    if (userCheck.length) {
      const updateSql = `update tbl_user_details set street=?, state=?, district=?, pin_code=?, landmark=? where user_id=?`;
      await runMysqlQueryWithParam(updateSql, [street, state, normalizedDistrict, normalizedPincode, landmark, user_id]);
    } else {
      const addSql = `insert into tbl_user_details (user_id, street, state, district, pin_code, landmark) values (?,?,?,?,?,?)`;
      await runMysqlQueryWithParam(addSql, [user_id, street, state, normalizedDistrict, normalizedPincode, landmark]);
    }
    return {
      status: true,
      msg: "Address updated successfully",
      responseObj: { street, state, district: normalizedDistrict, pin_code: normalizedPincode, landmark },
    };
  } catch (e) {
    console.log(e);
    return { status: false, msg: "Could not update address. Please try again", responseObj: [] };
  }
};

const validateAddressData = async (data) => {
  const normalizedPincode = `${data?.pincode || data?.pin_code || ""}`.trim();
  const normalizedDistrict = `${data?.district || ""}`.trim();
  const franchise = await getFranchiseForPincode(normalizedPincode);
  if (!normalizedPincode || !franchise?.user_id) {
    return { status: false, msg: OUT_OF_SERVICE_MSG };
  }
  const check = await runMysqlQueryWithParam("SELECT district FROM mst_pin_codes WHERE pin_code=?", [normalizedPincode]);
  if (!check.length) return { status: false, msg: OUT_OF_SERVICE_MSG };
  if (`${check[0].district || ""}`.trim().toLowerCase() !== normalizedDistrict.toLowerCase()) {
    return { status: false, msg: "District and pin code does not match" };
  }
  return { status: true, pincode: normalizedPincode, district: normalizedDistrict };
};

const getUserAddressList = async (user_id) => {
  try {
    await ensureAddressBookTable();
    const list = await runMysqlQueryWithParam(
      `SELECT id, label, recipient_name, phone_number, street, district, state, landmark, pin_code, is_default
       FROM tbl_user_addresses WHERE user_id=? ORDER BY is_default DESC, id DESC`,
      [user_id]
    );
    if (!list.length) {
      const legacy = await runMysqlQueryWithParam(
        "SELECT street, district, state, landmark, pin_code FROM tbl_user_details WHERE user_id=? AND street IS NOT NULL AND pin_code IS NOT NULL",
        [user_id]
      );
      if (legacy.length) {
        await runMysqlQueryWithParam(
          "INSERT INTO tbl_user_addresses (user_id, label, street, district, state, landmark, pin_code, is_default) VALUES (?,?,?,?,?,?,?,true)",
          [user_id, "Home", legacy[0].street, legacy[0].district, legacy[0].state, legacy[0].landmark, legacy[0].pin_code]
        );
        return getUserAddressList(user_id);
      }
    }
    return { status: true, msg: "Address list fetched successfully", responseObj: list };
  } catch (e) {
    console.log(e);
    return { status: false, msg: "Could not fetch address book. Please try again", responseObj: [] };
  }
};

const saveUserAddress = async (data, user_id) => {
  try {
    await ensureAddressBookTable();
    const validation = await validateAddressData(data);
    if (!validation.status) return { status: false, msg: validation.msg, responseObj: [] };

    const label = `${data.label || "Home"}`.trim() || "Home";
    const recipientName = `${data.recipient_name || data.recipientName || ""}`.trim() || null;
    const phoneNumber = `${data.phone_number || data.phoneNumber || ""}`.trim() || null;
    const street = `${data.street || ""}`.trim();
    const state = `${data.state || "West Bengal"}`.trim();
    const landmark = `${data.landmark || ""}`.trim();
    const addressId = Number(data.id || 0);
    const existing = await runMysqlQueryWithParam("SELECT id FROM tbl_user_addresses WHERE user_id=?", [user_id]);
    const shouldBeDefault = data.isDefault === true || data.is_default === true || !existing.length;

    if (!street) return { status: false, msg: "Please enter your street", responseObj: [] };

    if (shouldBeDefault) {
      await runMysqlQueryWithParam("UPDATE tbl_user_addresses SET is_default=false WHERE user_id=?", [user_id]);
    }

    let savedId = addressId;
    if (addressId) {
      const update = await runMysqlQueryWithParam(
        `UPDATE tbl_user_addresses
         SET label=?, recipient_name=?, phone_number=?, street=?, state=?, district=?, pin_code=?, landmark=?, is_default=?, updated_at=now()
         WHERE id=? AND user_id=?`,
        [label, recipientName, phoneNumber, street, state, validation.district, validation.pincode, landmark, shouldBeDefault, addressId, user_id]
      );
      if (!update.affectedRows) return { status: false, msg: "Address not found", responseObj: [] };
    } else {
      const insert = await runMysqlQueryWithParam(
        `INSERT INTO tbl_user_addresses
         (user_id, label, recipient_name, phone_number, street, state, district, pin_code, landmark, is_default)
         VALUES (?,?,?,?,?,?,?,?,?,?)`,
        [user_id, label, recipientName, phoneNumber, street, state, validation.district, validation.pincode, landmark, shouldBeDefault]
      );
      savedId = insert.insertId;
    }

    if (shouldBeDefault) {
      await syncDefaultAddressToUserDetails(user_id);
    }

    const addressList = await getUserAddressList(user_id);
    const savedAddress = addressList.responseObj.find((item) => Number(item.id) === Number(savedId)) || addressList.responseObj[0];
    return { status: true, msg: addressId ? "Address updated successfully" : "Address saved successfully", responseObj: { savedAddress, addressList: addressList.responseObj } };
  } catch (e) {
    console.log(e);
    return { status: false, msg: "Could not save address. Please try again", responseObj: [] };
  }
};

const syncDefaultAddressToUserDetails = async (user_id) => {
  const defaults = await runMysqlQueryWithParam("SELECT street, district, state, landmark, pin_code FROM tbl_user_addresses WHERE user_id=? AND is_default=true LIMIT 1", [user_id]);
  if (!defaults.length) return;
  const item = defaults[0];
  const userCheck = await runMysqlQueryWithParam("select id from tbl_user_details where user_id=?", [user_id]);
  if (userCheck.length) {
    await runMysqlQueryWithParam("update tbl_user_details set street=?, state=?, district=?, pin_code=?, landmark=? where user_id=?", [item.street, item.state, item.district, item.pin_code, item.landmark, user_id]);
  } else {
    await runMysqlQueryWithParam("insert into tbl_user_details (user_id, street, state, district, pin_code, landmark) values (?,?,?,?,?,?)", [user_id, item.street, item.state, item.district, item.pin_code, item.landmark]);
  }
};

